"""Download required model assets and verify every advertised voice before handoff."""
import numpy as np
import server

server.load_model()
if server.state != "ready":
    raise RuntimeError(server.load_error)
for voice in server.VOICES:
    audio, durations = server.generate_speech("Welcome to Geo Measure.", voice)
    if len(audio) == 0 or not np.isfinite(audio).all() or max(np.abs(audio)) == 0:
        raise RuntimeError(f"Invalid audio generated by {voice}")
    print(f"Verified {voice}: {sum(durations):.2f} seconds", flush=True)
print("All eight voices are ready.", flush=True)
